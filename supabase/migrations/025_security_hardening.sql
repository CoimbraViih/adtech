-- ─────────────────────────────────────────────────────────────────────────────
-- 9. ADMIN SELF-ESCALATION PREVENTION
--    An admin must not be able to UPDATE their own row to role='owner'.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION prevent_org_member_self_escalation()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp AS $$
BEGIN
  IF NEW.user_id = (SELECT auth.uid())
     AND OLD.role = 'admin'
     AND NEW.role = 'owner'
     AND NOT is_superadmin()
  THEN
    RAISE EXCEPTION 'admins cannot self-promote to owner';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS org_members_no_self_escalation ON organization_members;
CREATE TRIGGER org_members_no_self_escalation
  BEFORE UPDATE ON organization_members
  FOR EACH ROW EXECUTE FUNCTION prevent_org_member_self_escalation();

