// 30-day metric history for campaign cmp_001
export function getMockMetricSnapshots(campaignId: string): DailyMetricSnapshot[] {
  const base = campaignId === "cmp_001" ? 500 : campaignId === "cmp_002" ? 300 : 150;
  const snapshots: DailyMetricSnapshot[] = [];

  for (let i = 29; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().slice(0, 10);
    const variance = 0.7 + Math.random() * 0.6;
    const spend = +(base * variance).toFixed(2);
    const impressions = Math.round(spend * 120 * variance);
    const clicks = Math.round(impressions * 0.015);
    const conversions = Math.round(clicks * 0.017);
    const revenue = +(conversions * 150 * variance).toFixed(2);

    snapshots.push({
      date: dateStr,
      spend,
      impressions,
      clicks,
      conversions,
      revenue,
      roas: spend > 0 ? +(revenue / spend).toFixed(2) : 0,
      cpa: conversions > 0 ? +(spend / conversions).toFixed(2) : 0,
      ctr: impressions > 0 ? +(clicks / impressions * 100).toFixed(2) : 0,
    });
  }

  return snapshots;
}
